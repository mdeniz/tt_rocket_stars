
(function(){
 'use strict';
 const selectors=['#randomSplashRocket','#homeRocket','#garageRocket'];
 const ns='http://www.w3.org/2000/svg';
 const wrappers=new WeakMap();
 function install(host){
   if(!host)return null;
   const svg=host.querySelector('svg');
   if(!svg)return null;
   // Existing decoration uses a MutationObserver; wait for it to finish.
   const ship=svg.querySelector('.rocketShipMotion');
   if(!ship)return null;
   let visual=ship.querySelector(':scope > .rocketTapVisual');
   if(visual)return visual;
   // The actual spacecraft is the transformed group. Scenery, stars and
   // escort ships must remain outside the tap transform.
   const hull=[...ship.children].find(el=>el.tagName.toLowerCase()==='g' && el.hasAttribute('transform'));
   if(!hull)return null;
   visual=document.createElementNS(ns,'g');
   visual.setAttribute('class','rocketTapVisual');
   ship.insertBefore(visual,hull);
   visual.appendChild(hull);
   return visual;
 }
 function findHit(x,y){
   // Use the actual SVG geometry, independent of screen size, viewBox,
   // launch translation and which element receives the touch (clouds overlay).
   for(const selector of selectors){
     const host=document.querySelector(selector);
     if(!host||!host.getClientRects().length)continue;
     const visual=install(host);
     if(!visual)continue;
     const rect=visual.getBoundingClientRect();
     const pad=Math.min(13,Math.max(5,rect.width*.09));
     if(rect.width && rect.height && x>=rect.left-pad && x<=rect.right+pad && y>=rect.top-pad && y<=rect.bottom+pad)
       return {host,visual};
   }
   return null;
 }
 let recentShipTap=null;
 document.addEventListener('pointerdown',e=>{
   if(e.button!==undefined && e.button!==0)return;
   const hit=findHit(e.clientX,e.clientY);
   if(!hit)return;
   recentShipTap={host:hit.host,time:performance.now()};
   const visual=hit.visual;
   visual.classList.remove('rocketTapBounce');
   void visual.getBoundingClientRect(); // Restart on repeated rapid taps.
   visual.classList.add('rocketTapBounce');
   // Small tactile vibration on Android where supported (no permissions needed).
   try{if(navigator.vibrate)navigator.vibrate(20)}catch(_){}
   // Sound system is already unlocked on splash after the first touch.
   // Never create a second audio context or resume playback against user settings.
 },true);
 // On splash, tapping the rocket reacts instead of skipping the animation.
 // The first tap is intentionally allowed to start audio (v115 behavior).
 document.addEventListener('click',e=>{
   const tapped=recentShipTap;
   if(!tapped||performance.now()-tapped.time>850)return;
   recentShipTap=null;
   if(tapped.host.id==='randomSplashRocket'){
     const splash=document.getElementById('launchSplash');
     if(splash&&splash.classList.contains('splashAudioPlaying')){
       e.stopImmediatePropagation();
       e.stopPropagation();
     }
   }
 },true);
 // Ensure ships regenerated by profile changes and garage purchases get a
 // wrapper after the scene decorator's own MutationObserver has run.
 function boot(){
   const hosts=selectors.map(x=>document.querySelector(x)).filter(Boolean);
   hosts.forEach(host=>{
     install(host);
     const observer=new MutationObserver(()=>install(host));
     observer.observe(host,{childList:true});
   });
 }
 if(document.readyState==='loading')document.addEventListener('DOMContentLoaded',boot,{once:true});
 else boot();
})();

